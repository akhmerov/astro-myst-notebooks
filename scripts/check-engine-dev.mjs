async function command(executable,args,{timeout=120000}={}) {
  const child=spawn(executable,args,{cwd:root,env:{...process.env,ASTRO_TELEMETRY_DISABLED:'1'},stdio:['ignore','pipe','pipe'],detached:process.platform!=='win32'});
  let output=''; child.stdout.on('data',data=>{output+=data});child.stderr.on('data',data=>{output+=data});
  const timer=setTimeout(()=>{try{process.kill(-child.pid,'SIGKILL')}catch{child.kill('SIGKILL')}},timeout);
  try {
    const code=await new Promise((resolve,reject)=>{child.on('close',resolve);child.on('error',reject)});
    assert.equal(code,0,`${executable} ${args.join(' ')} failed\n${output.slice(-10000)}`);
    return output;
  } finally {clearTimeout(timer)}
}
function assertSourceMarkers(html) {
  const tree=fromHtml(html); const origins=[];
  visit(tree,'element',node=>{
    const raw=node.properties?.dataSourceLocation;
    if(!raw)return;
    const origin=JSON.parse(String(raw));
    const text=node.children.map(child=>child.type==='text'?child.value:'').join('');
    origins.push({origin,text});
  });
  return origins;
}
