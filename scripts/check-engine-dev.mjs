async function settled(expected,label){
  // A rebuild can reuse the execution cache and still loop. Observe MyST's
  // published manifest as well as the independent Python execution counter.
  const manifest=join(root,'_build/site/config.json');
  let modified=(await stat(manifest)).mtimeMs,quietSince=Date.now();
  await until(`${label} reaches an idle compiler`,async()=>{
    const current=(await stat(manifest)).mtimeMs;
    if(current!==modified){modified=current;quietSince=Date.now()}
    return Date.now()-quietSince>=3000;
  },15000);
  await pause(3000);
  assert.equal(await count(),expected,`${label}: Python execution did not settle`);
  assert.equal((await stat(manifest)).mtimeMs,modified,`${label}: MyST kept rebuilding after the page reloaded`);
}
